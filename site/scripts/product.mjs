// The generated half of the copy.
//
// A version or a flag list typed into a sentence is true the day it is typed and wrong in
// silence afterwards. So the site states neither: this reads them out of the application's
// own source on every build and writes src/lib/product.generated.ts, which the copy reaches
// through src/lib/product.ts.
//
// Two sources, both in this repository:
//   app/ChiakiNg.csproj            the version and the target framework
//   app/Session/HostCommandLine.cs the flags the host answers, with their summaries
//
// The second one is already held against the dispatch it describes by an assertion in the
// application's own suite, so what lands on the page is what the program answers.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(here, "..", "..");
const outPath = join(here, "..", "src", "lib", "product.generated.ts");

/** Read a file, or fail loudly: a missing source is a rename, not a reason to guess. */
function read(relative) {
  const full = join(repoRoot, relative);
  try {
    return readFileSync(full, "utf8");
  } catch {
    throw new Error(`product: ${relative} is not where the generator expects it`);
  }
}

function matchOrThrow(text, re, label, source) {
  const m = re.exec(text);
  if (!m) throw new Error(`product: ${source} no longer states ${label}`);
  return m[1].trim();
}

const csproj = read("app/ChiakiNg.csproj");
const version = matchOrThrow(csproj, /<Version>([^<]+)<\/Version>/, "a Version", "ChiakiNg.csproj");
const framework = matchOrThrow(
  csproj,
  /<TargetFramework>([^<]+)<\/TargetFramework>/,
  "a TargetFramework",
  "ChiakiNg.csproj",
);

// The Flags list, as C# record constructions: new("--name", "[arg]", "summary").
const hostCli = read("app/Session/HostCommandLine.cs");
const flagBlock = matchOrThrow(
  hostCli,
  /public static IReadOnlyList<HostFlag> Flags \{ get; \} =\s*\[([\s\S]*?)\];/,
  "a Flags list",
  "HostCommandLine.cs",
);
const flags = [...flagBlock.matchAll(/new\("(--[^"]+)",\s*"([^"]*)",\s*"([^"]+)"\)/g)].map((m) => ({
  name: m[1],
  argument: m[2],
  summary: m[3],
}));
if (flags.length === 0) {
  throw new Error("product: the Flags list parsed to nothing, so its shape has changed");
}

const banner = `// GENERATED by scripts/product.mjs on every build. Do not edit.
//
// The figures the copy states, read out of the application's own source rather than typed
// into a sentence. Regenerate with \`npm run generate\`; the build does it first.
`;

const body = `${banner}
export interface HostFlag {
  /** The flag itself, including its dashes. */
  readonly name: string;
  /** What follows it, or the empty string where nothing does. */
  readonly argument: string;
  /** One line: what running it does, not how. */
  readonly summary: string;
}

/** The application version, from app/ChiakiNg.csproj. */
export const VERSION = ${JSON.stringify(version)};

/** The target framework it builds against, from the same file. */
export const FRAMEWORK = ${JSON.stringify(framework)};

/** Every flag the host answers, in the order its own list declares them. */
export const HOST_FLAGS: readonly HostFlag[] = ${JSON.stringify(flags, null, 2)};
`;

writeFileSync(outPath, body);
console.log(
  `product: version ${version}, framework ${framework}, ${flags.length} host flags -> src/lib/product.generated.ts`,
);
